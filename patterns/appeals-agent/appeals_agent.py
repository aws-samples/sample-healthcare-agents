def get_system_prompt(ssm_path: str) -> str:
    """Fetch system prompt from Bedrock Prompt Management via SSM."""
    region = os.environ.get("AWS_REGION", os.environ.get("AWS_DEFAULT_REGION", "us-east-1"))
    ssm = boto3.client("ssm", region_name=region)
    prompt_arn = ssm.get_parameter(Name=ssm_path)["Parameter"]["Value"]

    bedrock = boto3.client("bedrock-agent", region_name=region)
    parts = prompt_arn.split(":")
    prompt_id = parts[-2].split("/")[-1]
    prompt_version = parts[-1]
    resp = bedrock.get_prompt(promptIdentifier=prompt_id, promptVersion=prompt_version)
    return resp["variants"][0]["templateConfiguration"]["text"]["text"]


def get_ssm_parameter(name: str) -> str:
    region = os.environ.get("AWS_REGION", os.environ.get("AWS_DEFAULT_REGION", "us-east-1"))
    ssm = boto3.client("ssm", region_name=region)
    return ssm.get_parameter(Name=name)["Parameter"]["Value"]


def create_gateway_mcp_client(access_token: str) -> MCPClient:
    stack_name = os.environ.get("STACK_NAME")
    if not stack_name:
        raise ValueError("STACK_NAME environment variable is required")

    gateway_url = get_ssm_parameter(f"/{stack_name}/gateway_url")

    return MCPClient(
        lambda: streamablehttp_client(
            url=gateway_url, headers={"Authorization": f"Bearer {access_token}"}
        ),
        prefix="gateway",
    )


def create_appeals_agent(user_id: str, session_id: str) -> Agent:
    prompt_ssm_path = os.environ.get("SYSTEM_PROMPT_SSM_PATH")
    if not prompt_ssm_path:
        raise ValueError("SYSTEM_PROMPT_SSM_PATH environment variable is required")

    system_prompt = get_system_prompt(prompt_ssm_path)

    model = BedrockModel(
        model_id="us.anthropic.claude-sonnet-4-5-20250929-v1:0",
        temperature=0.1,
    )

    memory_id = os.environ.get("MEMORY_ID")
    if not memory_id:
        raise ValueError("MEMORY_ID environment variable is required")

    session_manager = AgentCoreMemorySessionManager(
        agentcore_memory_config=AgentCoreMemoryConfig(
            memory_id=memory_id, session_id=session_id, actor_id=user_id
        ),
        region_name=os.environ.get("AWS_DEFAULT_REGION", "us-east-1"),
    )

    access_token = get_gateway_access_token()
    gateway_client = create_gateway_mcp_client(access_token)

    return Agent(
        name="AppealsAgent",
        system_prompt=system_prompt,
        tools=[
            gateway_client,
            check_appeal_deadline,
            validate_and_assemble_appeal,
            save_appeal_letter,
        ],
        model=model,
        session_manager=session_manager,
        trace_attributes={"user.id": user_id, "session.id": session_id},
    )


@app.entrypoint
async def agent_stream(payload):
    user_query = payload.get("prompt")
    user_id = payload.get("userId")
    session_id = payload.get("runtimeSessionId")

    if not all([user_query, user_id, session_id]):
        yield {"status": "error", "error": "Missing required fields: prompt, userId, or runtimeSessionId"}
        return

    try:
        agent = create_appeals_agent(user_id, session_id)
        async for event in agent.stream_async(user_query):
            yield event
    except Exception as e:
        traceback.print_exc()
        yield {"status": "error", "error": str(e)}


if __name__ == "__main__":
    app.run()
