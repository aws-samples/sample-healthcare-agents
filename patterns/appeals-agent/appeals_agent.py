"""
Appeals Agent using Strands SDK.

Generates appeal letters for denied claims with deterministic validation,
deadline compliance checking, and structured letter assembly. Consults
payer rules via Gateway KB tools and saves final letters to S3.
"""

import json
import os
import time
import traceback
from dataclasses import asdict

import boto3
from bedrock_agentcore.runtime import BedrockAgentCoreApp
from bedrock_agentcore.memory.integrations.strands.config import AgentCoreMemoryConfig
from bedrock_agentcore.memory.integrations.strands.session_manager import (
    AgentCoreMemorySessionManager,
)
from gateway.utils.gateway_access_token import get_gateway_access_token
from mcp.client.streamable_http import streamablehttp_client
from strands import Agent, tool
from strands.models import BedrockModel
from strands.tools.mcp import MCPClient

from appeal_letter_builder import (
    AppealLetterComponents,
    DenialInfo,
    PatientInfo,
    ProviderInfo,
    validate_and_build,
)
from deadline_tracker import check_filing_deadline

app = BedrockAgentCoreApp()

s3_client = boto3.client("s3")
APPEALS_BUCKET = os.environ.get("APPEALS_BUCKET", "")


